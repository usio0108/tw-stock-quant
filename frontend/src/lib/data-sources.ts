// 真實：資料來自外部來源，或用標準公式對真實資料做確定性計算。
// 估算：用簡化規則或自訂口徑推算，數字可能與交易所／券商不同。
// 示範資料：假資料，只為了讓版面完整，不能拿來做任何決策。
export type DataStatus = "真實" | "估算" | "示範資料"

export const STATUS_DESCRIPTIONS: Record<DataStatus, string> = {
  真實: "資料來自外部來源，或用標準公式對真實資料計算而得。",
  估算: "用簡化規則或自訂口徑推算，可能與交易所、券商的數字不同，僅供參考。",
  示範資料: "假資料，只是先把版面做出來；不是真實市場數據，請勿用來做投資判斷。",
}

export interface DataEntry {
  id: string // 錨點用，全站唯一
  name: string // 畫面上看到的名稱
  where?: string // 出現的位置（頁面 > 分頁／區塊）
  meaning: string // 它在觀察什麼：白話意義，必要時附例子或尺度
  source: string // 實際來源（欄位／資料集／檔案）
  status: DataStatus
  unit: string
  update: string // 更新頻率與快取（中台 TTL、頁面刷新）
  caveats: string[] // 已知限制與容易誤解之處
}

export interface DataSection {
  id: string
  title: string
  route: string
  summary: string
  entries: DataEntry[]
}

